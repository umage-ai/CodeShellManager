//! The generated tool catalogue in `docs/tools.md`.
//!
//! Only the block between the two markers is generated (the rest of the file is written by hand,
//! with the design notes and the planned tools). `cargo xtask tools` rewrites the block;
//! `cargo xtask tools --check` fails when it is out of date. The table is the **engine**
//! registry: tools the app adds itself (`csm-ui`'s pane tools and stand-ins) are not in it.

use csm_engine::{Effects, Engine, State};

use crate::Findings;

pub const BEGIN: &str = "<!-- xtask:tools:begin (generated by `cargo xtask tools`; do not edit by hand) -->";
pub const END: &str = "<!-- xtask:tools:end -->";

const EFFECT_WORDS: &[(Effects, &str)] = &[
    (Effects::CHANGES_UI_STATE, "ui"),
    (Effects::MUTATES_STATE, "state"),
    (Effects::LAUNCHES_PROCESS, "launch"),
    (Effects::SENDS_INPUT, "input"),
    (Effects::MAY_DISCARD_DATA, "discard"),
    (Effects::WRITES_FILESYSTEM, "files"),
    (Effects::ACCESSES_NETWORK, "network"),
    (Effects::READS_SESSION_CONTENT, "content"),
    (Effects::STORES_SECRETS, "secrets"),
];

/// `read` for a tool that only reads, else the effect words.
pub fn effects_text(e: Effects) -> String {
    let words: Vec<&str> = EFFECT_WORDS.iter().filter(|(f, _)| e.contains(*f)).map(|(_, w)| *w).collect();
    if words.is_empty() { "read".to_owned() } else { words.join(", ") }
}

/// The generated block, markers included.
pub fn generate() -> Result<String, String> {
    let engine = Engine::start(State::default(), Vec::new()).map_err(|e| format!("could not start an engine: {e}"))?;
    let mut rows = String::new();
    for spec in engine.registry().all() {
        let summary = spec.summary.replace('|', "\\|").replace('\n', " ");
        let consent = if spec.effects.needs_consent() { "asks" } else { "no" };
        rows.push_str(&format!("| `{}` | {} | {} | {} | {} |\n", spec.id, spec.toolset.id(), effects_text(spec.effects), consent, summary));
    }
    let count = engine.registry().all().len();
    engine.shutdown();
    Ok(format!(
        "{BEGIN}\n\n### Engine registry ({count} tools)\n\nGenerated from `csm-engine`'s registry. \"asks\" means an MCP caller waits for the person's consent.\n\n| id | toolset | effects | MCP consent | what |\n|---|---|---|---|---|\n{rows}\n{END}"
    ))
}

/// `doc` with the generated block replaced (or appended when the markers are missing).
pub fn splice(doc: &str, block: &str) -> String {
    let normalized = doc.replace("\r\n", "\n");
    match (normalized.find(BEGIN), normalized.find(END)) {
        (Some(a), Some(b)) if a < b => format!("{}{}{}", &normalized[..a], block, &normalized[b + END.len()..]),
        _ => format!("{}\n\n## Generated catalogue\n\n{block}\n", normalized.trim_end()),
    }
}

pub fn run(check: bool) -> Result<Findings, String> {
    let path = crate::root().join("docs").join("tools.md");
    let current = std::fs::read_to_string(&path).map_err(|e| format!("could not read {}: {e}", path.display()))?;
    let wanted = splice(&current, &generate()?);
    let same = wanted == current.replace("\r\n", "\n");
    if check {
        return Ok(if same {
            Vec::new()
        } else {
            vec!["docs/tools.md is out of date with the engine registry; run `cargo xtask tools` and commit".to_owned()]
        });
    }
    if !same {
        // Keep the file's own line endings.
        let out = if current.contains("\r\n") { wanted.replace('\n', "\r\n") } else { wanted };
        std::fs::write(&path, out).map_err(|e| format!("could not write {}: {e}", path.display()))?;
        println!("updated docs/tools.md");
    }
    Ok(Vec::new())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn splice_replaces_only_the_block_and_appends_when_missing() {
        let block = format!("{BEGIN}\nnew\n{END}");
        let doc = format!("intro\n{BEGIN}\nold\n{END}\noutro\n");
        assert_eq!(splice(&doc, &block), format!("intro\n{block}\noutro\n"));
        let appended = splice("intro\n", &block);
        assert!(appended.starts_with("intro\n") && appended.contains(&block));
        assert_eq!(splice(&appended, &block), appended, "idempotent");
    }

    #[test]
    fn effect_words() {
        assert_eq!(effects_text(Effects::READ_ONLY), "read");
        assert_eq!(effects_text(Effects::MUTATES_STATE | Effects::LAUNCHES_PROCESS), "state, launch");
    }
}
